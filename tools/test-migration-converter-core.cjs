const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
async function sourceModule(name) { return import('data:text/javascript;base64,' + fs.readFileSync(path.join('assets/migration', name)).toString('base64')); }
(async () => {
  const core = await sourceModule('core.js'), files = await sourceModule('files.js');
  const guardian = ['①','②'].flatMap(n => ['姓','名','姓カナ','名カナ','続柄','メールアドレス','電話番号','勤務先','勤務先住所','勤務先電話番号'].map(h => `保護者${n}${h}`));
  const schemas = [
    {id:'families',label:'家庭',headers:['ID','家庭名','住所','電話番号',...guardian]},
    {id:'children',label:'園児',headers:['ID','姓','名','姓カナ','名カナ','生年月日','入園日','退園日','在園状態','クラス名','家庭ID','家庭名','住所','電話番号','照合用氏名','照合用氏名種別','性別']},
  ];
  assert.equal(core.dateValue('令和元年5月1日'), '2019-05-01');
  assert.equal(core.dateValue('H31.4.30'), '2019-04-30');
  assert.throws(() => core.dateValue('平成31年5月1日'));
  assert.throws(() => core.dateValue('2025-02-29'));
  assert.equal(core.dateValue(1), '1900-01-01');
  assert.equal(core.dateValue(61), '1900-03-01');
  assert.throws(() => core.dateValue(60));
  assert.equal(core.dateValue(1, true), '1904-01-02');
  assert.equal(core.dateValue(0, true), '1904-01-01');
  assert.equal(core.transformValue('やまだ たろう','given_kana'),'タロウ');
  assert.throws(() => core.transformValue('山田太郎','surname'));
  assert.equal(core.transformValue('女児','sex'),'female');
  assert.throws(() => core.transformValue('1','sex'));
  const parsed = files.parseDelimited('\ufeff"a","b"\r\n"x\ny","q""z"\r\n');
  assert.deepEqual(parsed[1].values, ['x\ny','q"z']);
  assert.throws(() => files.parseDelimited('a,b\n"notclosed'));
  assert.throws(() => files.parseDelimited('a,b\n"x"oops,y'));
  assert.equal((await files.readSource(new File(['姓\t名\n山田\t太郎'],'data.tsv'))).encoding.includes('タブ'),true);
  assert.equal((await files.readSource(new File(['姓;名\n山田;太郎'],'data.csv'))).encoding.includes('セミコロン'),true);
  const utf16 = Buffer.concat([Buffer.from([255,254]),Buffer.from('姓,名\r\n山田,太郎','utf16le')]);
  assert.equal((await files.readSource(new File([utf16],'utf16.csv'))).encoding.includes('UTF-16'),true);
  const sheet = {rows:[{line:1,values:['台帳']},{line:2,values:['園児','','保護者']},{line:3,values:['姓','名','氏名']},{line:4,values:['山田','太郎','山田 花子']}],merges:['A2:B2']};
  assert.deepEqual(files.sourceTable(sheet,2,2).headers.map(h=>h.name),['園児 / 姓','園児 / 名','保護者 / 氏名']);
  const targets = core.makeTargets('combined',1,schemas);
  const names = ['移行元ID','家族番号','家庭名','園児氏名','フリガナ','生年月日','入園日','クラス','保護者名①','保護者①携帯電話番号','保護者①勤務先名'];
  const headers = names.map(name=>({name,label:name}));
  const mappings = Object.fromEntries(targets.map(t=>[t.key,core.suggestMapping(t,headers)]));
  assert.equal(mappings['children:1:ID'].column,null);
  assert.equal(mappings['children:1:姓'].column,3);
  assert.equal(mappings['children:1:名'].transform,'given');
  assert.equal(mappings['families:0:保護者①姓'].column,8);
  assert.equal(mappings['families:0:保護者①名'].transform,'given');
  const givenTarget=targets.find(t=>t.header==='保護者①名');
  assert.equal(core.suggestMapping(givenTarget,[{name:'保護者①名'}]).transform,'copy');
  mappings['children:1:クラス名'].replacements='A=検証クラス';
  const rows = [
    {line:2,values:['999','F1','山田家','山田 太郎','やまだ たろう','令和4年4月1日','2025/4/1','A','山田 花子','09012345678','ひかり商店']},
    {line:3,values:['1000','F1','山田家','山田 次郎','やまだ じろう','2023/5/1','2025/4/1','A','山田 花子','09012345678','ひかり商店']},
  ];
  const opts = {mode:'combined',childCount:1,familyKey:1,epoch:false,allowIds:false,headerDepth:1};
  let result=core.convertRows(rows,targets,mappings,opts,schemas);
  assert.equal(result.outputs.families.rows.length,1);
  assert.equal(result.outputs.children.rows.length,2);
  assert.deepEqual(core.validateResult(result),[]);
  assert.equal(result.outputs.children.rows[0].values.ID,'');
  assert.equal(result.outputs.children.rows[0].values['クラス名'],'検証クラス');
  assert.equal(result.outputs.families.rows[0].values['保護者①電話番号'],'09012345678');
  assert.equal(result.outputs.families.rows[0].values['保護者①姓'],'山田');
  assert.equal(result.outputs.families.rows[0].values['保護者①名'],'花子');
  result.outputs.families.rows[0].values['家庭名']='山田家（東）';
  core.validateResult(result);
  assert.equal(result.outputs.children.rows[1].values['家庭名'],'山田家（東）');
  result.outputs.families.rows[0].include=false;
  assert(core.validateResult(result).some(i=>i.header==='家庭名'));
  result=core.convertRows(rows,targets,mappings,{...opts,familyKey:null},schemas);
  assert.equal(result.outputs.families.rows.length,2);
  assert(core.validateResult(result).some(i=>i.message.includes('重複')));
  const conflicts=structuredClone(rows);conflicts[1].values[9]='08011112222';
  result=core.convertRows(conflicts,targets,mappings,opts,schemas);
  assert(core.validateResult(result).some(i=>i.message.includes('値が異なり')));
  const profile=core.saveProfile(headers,targets,mappings,opts);
  mappings['children:1:入園日'].fallback='secret-fallback';
  assert(!JSON.stringify(core.saveProfile(headers,targets,mappings,opts)).includes('secret-fallback'));
  assert(!JSON.stringify(profile).includes('山田 花子'));
  const reordered=[...headers].reverse(),loaded=core.loadProfile(profile,reordered,targets);
  assert.equal(reordered[loaded.mapping['children:1:姓'].column].name,'園児氏名');
  assert.equal(loaded.familyKey,9);
  const duplicate=[...headers,{name:'園児氏名',label:'duplicate'}];
  assert(core.loadProfile(profile,duplicate,targets).missing.some(m=>m.includes('同名列')));
  assert.throws(()=>core.loadProfile({...profile,mappings:[{...profile.mappings[0],transform:'eval'}]},headers,targets));
  const dangerous=structuredClone(rows);dangerous[0].values[10]='=HYPERLINK("bad")';
  result=core.convertRows(dangerous,targets,mappings,opts,schemas);
  assert(core.validateResult(result).some(i=>i.message.includes('先頭文字')));
  const missingFormula=structuredClone(rows);missingFormula[0].formulaMissing=[9];
  assert(core.validateResult(core.convertRows(missingFormula,targets,mappings,opts,schemas)).some(i=>i.message.includes('計算結果')));
  const csv=core.csvText(core.convertRows(rows,targets,mappings,opts,schemas).outputs.families);
  assert.equal(files.parseDelimited(csv)[0].values.length,24);
  const four=core.makeTargets('combined',4,schemas);
  const t=four.find(t=>t.slot===4&&t.header==='姓');
  assert.equal(core.suggestMapping(t,[{name:'お子様の名前④'}]).transform,'surname');
  const guardianHeaders=['家族番号','家庭名','区分','氏名','電話番号'].map(name=>({name,label:name}));
  const guardianTargets=core.makeTargets('guardian_rows',1,schemas);
  assert.equal(core.suggestMapping(guardianTargets.find(t=>t.header==='保護者①名'),[{name:'保護者名'}]).transform,'given');
  assert.equal(core.suggestMapping(guardianTargets.find(t=>t.header==='保護者①名カナ'),[{name:'保護者名カナ'}]).transform,'given_kana');
  const guardianMappings=Object.fromEntries(guardianTargets.map(t=>[t.key,core.suggestMapping(t,guardianHeaders)]));
  const guardianOptions={mode:'guardian_rows',familyKey:0,guardianColumn:2,guardianFirst:'父',guardianSecond:'母',childCount:1,headerDepth:1};
  const guardianRows=[{line:2,values:['F1','佐藤家','父','佐藤 太郎','09011112222']},{line:3,values:['F1','佐藤家','母','佐藤 花子','08033334444']}];
  result=core.convertRows(guardianRows,guardianTargets,guardianMappings,guardianOptions,schemas);
  assert.deepEqual(core.validateResult(result),[]);
  assert.equal(result.outputs.families.rows.length,1);
  assert.equal(result.outputs.families.rows[0].values['保護者②名'],'花子');
  assert.equal(result.outputs.families.rows[0].values['保護者①電話番号'],'09011112222');
  assert.equal(result.outputs.families.rows[0].values['電話番号'],'');
  assert.throws(()=>core.convertRows(guardianRows,guardianTargets,guardianMappings,{...guardianOptions,familyKey:null},schemas));
  const unknown=structuredClone(guardianRows);unknown[1].values[2]='祖父';
  result=core.convertRows(unknown,guardianTargets,guardianMappings,guardianOptions,schemas);
  assert(core.validateResult(result).some(i=>i.header==='元データ'));
  result.outputs.families.rows[0].values['家庭名']='別の名前';
  result.outputs.families.rows[0].inputErrors={};
  assert(core.validateResult(result).some(i=>i.header==='元データ'));
  const guardianProfile=core.saveProfile(guardianHeaders,guardianTargets,guardianMappings,guardianOptions);
  assert.equal(core.loadProfile(guardianProfile,guardianHeaders,guardianTargets).guardianSecond,'母');
  console.log('PASS: date/kana/name transforms, CSV/TSV/UTF-16, multi-row headers, conservative matching, household grouping/conflicts, ID protection, editable links, presets, formulas and CSV output');
})().catch(error=>{console.error(error.message);console.error(error.stack?.split('\n').filter(line=>!line.includes('data:text')).slice(0,5).join('\n'));process.exitCode=1;});
