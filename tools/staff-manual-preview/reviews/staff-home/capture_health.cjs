// Capture the deployed pages as an ordinary editor, in a disposable health fixture.
const {chromium} = require('playwright');
const {spawn} = require('node:child_process');
const {once} = require('node:events');
const readline = require('node:readline');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../../../..');
const out = path.join(root, 'docs/manual-guide-preview/health/images');
const chart = process.env.HEALTH_CHART_JS || path.join(root,'.local-dev/manual-health-20261109/chart.umd.min.js');

async function run() {
  fs.mkdirSync(out, {recursive:true});
  const server=spawn(path.join(root,'venv/Scripts/python.exe'),['-X','utf8',path.join(__dirname,'health_fixture.py')],
    {cwd:root,windowsHide:true,stdio:['ignore','pipe','inherit']});
  let browser;
  try {
    const line=readline.createInterface({input:server.stdout});
    const {origin,cookies}=JSON.parse(await Promise.race([once(line,'line').then(v=>v[0]),once(server,'exit').then(()=>{throw Error('Fixture stopped');})]));
    assert.match(origin,/^http:\/\/127\.0\.0\.1:\d+$/);
    browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
    const ctx=await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1.3,locale:'ja-JP'});
    await ctx.addCookies(Object.entries(cookies).map(([name,value])=>({name,value,url:origin})));
    await ctx.route('**/*',r=>{
      const u=new URL(r.request().url());
      if(u.origin===origin) return r.continue();
      if(u.hostname==='cdn.tailwindcss.com') return r.fulfill({path:path.join(root,'tools/staff-manual-preview/dist/assets/tailwind.js'),contentType:'application/javascript'});
      if(u.href==='https://cdn.jsdelivr.net/npm/chart.js@4.4.3/dist/chart.umd.min.js') return r.fulfill({path:chart,contentType:'application/javascript'});
      return r.abort();
    });
    const p=await ctx.newPage();
    p.setDefaultTimeout(6000);
    const by=(role,name)=>p.getByRole(role,{name,exact:true});
    const link=name=>by('link',name);
    const button=name=>by('button',name);
    const heading=name=>by('heading',name);
    const txt=name=>p.getByText(name,{exact:true});
    const field=name=>p.locator('[name="'+name+'"]').first();
    const label=name=>field(name).locator('..');
    const go=url=>p.goto(origin+url);
    async function shot(file,...boxes) {
      await boxes[0].scrollIntoViewIfNeeded();
      await p.evaluate(()=>document.fonts.ready);
      const bounds=await Promise.all(boxes.map(el=>el.evaluate(e=>{
        const b=e.getBoundingClientRect();return [b.left+scrollX,b.top+scrollY,b.right+scrollX,b.bottom+scrollY];
      })));
      const x=Math.max(0,Math.floor(Math.min(...bounds.map(b=>b[0])))-5);
      const y=Math.max(0,Math.floor(Math.min(...bounds.map(b=>b[1])))-5);
      const right=Math.min(1440,Math.ceil(Math.max(...bounds.map(b=>b[2])))+5);
      const bottom=Math.ceil(Math.max(...bounds.map(b=>b[3])))+5;
      await p.screenshot({path:path.join(out,file+'.jpg'),quality:92,fullPage:true,clip:{x,y,width:right-x,height:bottom-y}});
    }
    const row=name=>p.locator('tbody tr').filter({hasText:name});
    await go('/health');
    await shot('menu',link('健康管理'));
    await row('見本 あおい').getByRole('link',{name:'健康サマリー'}).click();
    await shot('summary-links',heading('見本 あおい の健康サマリー').locator('../..'));
    await link('健康プロフィール').click();
    await field('primary_doctor_name').fill('見本こども医院');
    await field('has_allergy').check();
    await field('other_management_items').fill('生活管理指導表を確認');
    await shot('profile-basic',heading('基本医療情報'),label('primary_doctor_name'));
    await shot('profile-flags',heading('重点管理項目').locator('..'));
    await field('other_notes').fill('資料を確認した日　11月9日');
    await shot('profile-save',label('other_notes'),button('保存する'));
    await button('保存する').click(); await txt('健康プロフィールを更新しました。').waitFor();
    await p.reload();assert.equal(await field('primary_doctor_name').inputValue(),'見本こども医院');
    await shot('profile-saved',txt('健康プロフィールを更新しました。'));
    await link('健康サマリーへ').click();
    await link('アレルギー管理').click();
    await button('追加する').click();await txt('アレルゲン名は必須です。').waitFor();
    await shot('allergy-error',txt('アレルゲン名は必須です。'));
    await field('allergen_category').selectOption('food_mandatory');
    await field('allergen_name').fill('卵');
    await field('valid_until').fill('2026-11-05');
    await field('source_document').fill('生活管理指導表（見本）');
    await shot('allergy-form',heading('新しいアレルギーを追加'),label('allergen_name'),label('severity'));
    await shot('allergy-date',label('diagnosis_date'),label('valid_until'));
    await shot('allergy-add',button('追加する'));
    await button('追加する').click();await txt('アレルギー情報を追加しました。').waitFor();
    await shot('allergy-active',heading('登録済みアレルギー'),heading('登録済みアレルギー').locator('..').locator('div.rounded-xl').first());
    await link('編集する').click();
    await field('notes').fill('資料を再確認');
    await shot('allergy-update',label('notes'),button('更新する'));
    await button('更新する').click();await txt('アレルギー情報を更新しました。').waitFor();
    await button('解除する').click();await txt('解除済み').waitFor();
    await shot('allergy-inactive',heading('登録済みアレルギー'),heading('登録済みアレルギー').locator('..').locator('div.rounded-xl').first());
    await button('再有効化する').click();await txt('アレルギー情報を再有効化しました。').waitFor();
    await link('健康一覧へ').click();
    await shot('overview',heading('健康管理一覧').locator('../..'),txt('表示園児数').locator('../..'));
    await field('q').fill('あおい');
    await field('attention').selectOption('needs_attention');
    await field('classroom_id').selectOption({label:'ひよこ組'});
    await button('絞り込む').click();await row('見本 あおい').waitFor();assert.equal(await p.locator('tbody tr').count(),1);
    await shot('filter',p.locator('form[action="/health"]'));
    await shot('filtered-row',p.locator('table'));
    await field('q').fill('該当なし');await button('絞り込む').click();await txt('該当する園児がありません。').waitFor();
    await shot('empty',link('リセット'),p.locator('table'));
    await link('リセット').click();await row('見本 ひなた').waitFor();assert.equal(await p.locator('tbody tr').count(),2);
    const mixed=row('見本 ひなた');
    assert.match(await mixed.innerText(),/93\.0 cm/);assert.match(await mixed.innerText(),/14\.0 kg/);
    const joined=await mixed.locator('td').nth(4).innerText();
    assert.ok(joined.includes('2026-05-12') && !joined.includes('2026-05-13'));
    await mixed.getByRole('link',{name:'健康サマリー'}).click();
    assert.ok((await txt('最新体重').locator('..').innerText()).includes('2026-05-13'));
    await txt('記録は最新です').waitFor();await txt('定期健診記録が確認できています。').waitFor();
    await link('健康一覧へ').click();
    await row('見本 あおい').getByRole('link',{name:'健康サマリー'}).click();
    await shot('summary-status',txt('最新身長').locator('../..'));
    await shot('summary-allergy',heading('アレルギー情報').locator('../..'));
    await link('健診記録とグラフ').click();
    await field('checked_at').fill('');
    const [invalid]=await Promise.all([p.waitForResponse(r=>r.request().method()==='POST' && r.url().endsWith('/check-records')),button('記録を追加する').click()]);
    assert.equal(invalid.status(),422);
    assert.ok((await invalid.json()).detail.some(e=>e.loc.includes('checked_at')));
    await p.goBack();await field('checked_at').waitFor();
    await field('check_type').selectOption('periodic');
    await field('checked_at').fill('2026-11-09');
    await field('height_cm').fill('97.0');await field('weight_kg').fill('15.2');
    await shot('record-form',heading('健診記録を追加'),label('checked_at'),label('weight_kg'),label('height_cm'));
    await field('observer_name').fill('見本 はなこ');
    await shot('record-save',label('followup_notes'),button('記録を追加する'));
    await button('記録を追加する').click();await txt('健康診断記録を追加しました。').waitFor();
    await shot('record-list',heading('測定一覧'),heading('測定一覧').locator('..').locator('table'));
    await row('2026-11-09').getByRole('link',{name:'訂正'}).click();
    await field('correction_reason').fill('測定票の数字を転記し直しました');
    await field('weight_kg').fill('15.0');
    await shot('correction',heading('健診記録を訂正'),label('correction_reason'),label('weight_kg'));
    await shot('correction-save',button('訂正を保存する'));
    await button('訂正を保存する').click();await txt('健診記録を訂正し、変更履歴を保存しました。').waitFor();
    await p.reload();await row('2026-11-09').getByText('15.0 kg').waitFor();
    await p.locator('details summary').filter({hasText:'測定票の数字'}).click();
    await shot('history',heading('訂正履歴').locator('..'));
    await link('在籍期間すべて').click();
    await p.waitForFunction(()=>window.Chart?.getChart('weight-chart')?.data.labels.length===4);
    await p.locator('#weight-chart').scrollIntoViewIfNeeded();
    // Capture only once the real Chart.js plots finish their initial animation.
    await p.evaluate(()=>{for(const id of ['height-chart','weight-chart']) window.Chart.getChart(id).update('none');});
    await shot('chart-period',heading('身長・体重グラフ').locator('../..'));
    await shot('chart',heading('身長推移').locator('../..'));
    await link('直近1年').click();await p.waitForFunction(()=>window.Chart?.getChart('weight-chart')?.data.labels.length===3);
    await go('/children/1/health/profile?as=view_only');
    await field('primary_doctor_name').waitFor();
    assert.equal(await button('保存する').count(),0);
    assert.equal(await field('primary_doctor_name').isEditable(),true);
    await field('primary_doctor_name').fill('保存されない見本');
    await p.reload();assert.equal(await field('primary_doctor_name').inputValue(),'見本こども医院');
    console.log('Verified ordinary editor, view-only, save and reopen, filter, restore allergy, correction history, both chart ranges and date discrepancies.');
  } finally { if(browser) await browser.close(); server.kill(); }
}
run().catch(e=>{console.error(e);process.exitCode=1;});
