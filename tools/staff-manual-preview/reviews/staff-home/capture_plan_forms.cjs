// Capture the ordinary staff workflow against a disposable database, then reopen each saved sheet.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const readline = require('node:readline');
const {once} = require('node:events');
const {spawn} = require('node:child_process');
const out = process.env.PLAN_FORM_CAPTURE_DIR || path.join(__dirname, 'plan-forms');
const root = path.resolve(__dirname, '../../../..');

async function main() {
  fs.mkdirSync(out, {recursive:true});
  const server = spawn(path.join(root,'venv/Scripts/python.exe'), ['-X','utf8',path.join(__dirname,'plan_form_fixture.py')],
    {cwd:root, windowsHide:true, stdio:['ignore','pipe','inherit']});
  let browser;
  try {
    const lines = readline.createInterface({input:server.stdout});
    const origin = await Promise.race([once(lines,'line').then(([value])=>value),
      once(server,'exit').then(([code])=>{throw Error('Fixture exited: '+code);})]);
    assert.match(origin,/^http:\/\/127\.0\.0\.1:\d+$/);
    browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
    const page = await browser.newPage({viewport:{width:1490,height:1050},deviceScaleFactor:1.25,locale:'ja-JP'});
    page.setDefaultTimeout(6500);
    page.on('pageerror', e=>console.error('Page:',e.message));
    page.on('response', r=>{if(r.status()>=400)console.error(r.status(),r.url());});
    await page.route('**/*', async route=>{
      const url = new URL(route.request().url());
      if (url.origin===origin) return route.continue();
      if (url.hostname==='cdn.tailwindcss.com') return route.fulfill({path:path.resolve(__dirname,'../../dist/assets/tailwind.js'),contentType:'text/javascript'});
      if (url.hostname==='unpkg.com') return route.fulfill({body:'',contentType:'text/javascript'});
      return route.abort();
    });
    const loc = s=>page.locator(s).first();
    async function shot(name, selector, last) {
      const el = loc(selector);
      await el.waitFor();
      if (page.viewportSize().width < 1024) {
        await page.waitForFunction(()=>(document.querySelector('#staff-sidebar')?.getBoundingClientRect().right??0)<=1);
      }
      await el.scrollIntoViewIfNeeded();
      await page.evaluate(()=>document.fonts.ready);
      if(!last) return el.screenshot({path:path.join(out,name+'.jpg'),quality:94});
      const b=await el.boundingBox(), e=await loc(last).boundingBox(), scroll=await page.evaluate(()=>({x:scrollX,y:scrollY}));
      const x=Math.max(0,Math.min(b.x,e.x)), y=Math.min(b.y,e.y);
      const right=Math.min(1490,Math.max(b.x+b.width,e.x+e.width));
      await page.screenshot({path:path.join(out,name+'.jpg'),quality:94,fullPage:true,clip:{x:x+scroll.x,y:y+scroll.y,width:right-x,height:Math.max(b.y+b.height,e.y+e.height)-y}});
    }
    const shown = async (selector, text)=>page.locator(selector).filter({hasText:text}).first().waitFor();
    const go = uri=>page.goto(origin+uri);
    async function openPeriod(type, key, age, room='1') {
      const monthly=type==='monthly';
      await go('/plans/'+type+'-plans/');
      const filters=page.locator('.calendar-filters');
      await filters.locator('[name=classroom_id]').selectOption(room);
      await filters.locator('[name=age]').selectOption(age);
      await filters.locator(monthly?'[name=year]':'[name=month]').fill(monthly?'2026':'2026-11');
      await filters.getByRole('button',{name:'表示'}).click();
      return page.locator('[data-period="'+key+'"]');
    }
    await go('/plans/');
    await loc('.period-links a[href="/plans/annual-library"]').click();
    await loc('#annual-year').fill('2026');
    await loc('#annual-year').press('Tab');
    await loc('#annual-origin').selectOption('source:sample');
    const resize=(width)=>page.setViewportSize({width,height:1050});
    await resize(680);
    await shot('annual-choose','.annual-pickers','.annual-origin');
    await loc('#annual-import').click();
    await resize(1490);
    const aim='身近な自然に触れ、好きな遊びを楽しむ。';
    await loc('[data-edit=annual]').fill(aim);
    await shot('annual-goal','.rd-meta th:has-text("年間の")','.rd-annual');
    await loc('[data-select="development-1"]').click();
    await loc('[data-confirm="development-1"]').check();
    await shot('annual-timing','.rd-entry[data-id="development-1"]');
    await shot('annual-save','.annual-actions');
    await loc('#annual-save').click();
    await shown('#annual-message','年案を保存しました');
    await page.reload();
    assert.equal(await loc('[data-edit=annual]').inputValue(),aim);
    await shot('annual-saved','.rd-chrome strong','.annual-document-link');
    await loc('[data-reflection="0:0"]').fill('園庭で好きな遊びを選ぶ姿が増えた。');
    await loc('#reflection-save').click();
    await shown('#annual-reflection-editor','反省の下書きを保存しました');
    await resize(730);
    await shot('annual-reflection','.reflection-top','.reflection-grid [data-reflection="0:0"]');
    await shot('annual-review','.reflection-review-controls label','#reflection-review');
    await resize(1490);
    console.log('Year saved and reopened.');

    let card=await openPeriod('monthly','2026-11','1');
    await shot('monthly-choose','[data-period="2026-11"]');
    await card.getByText('自園の帳票で作成').click();
    const goal='戸外で落ち葉の色や音を楽しむ。';
    await loc('[data-cell="common:goal"]').fill(goal);
    await shot('monthly-goal','#form .common');
    await loc('#child').selectOption('child:1');
    await loc('[data-cell="child:1:life"]').click();
    await shown('.candidate','タオル');
    await shot('monthly-example','.library .target','.library #candidates');
    await loc('.candidate').click();
    assert.ok((await loc('[data-cell="child:1:life"]').inputValue()).includes('タオル'));
    await shot('monthly-export','#print-monthly','#excel-monthly');
    const popup = page.waitForEvent('popup');
    await loc('#print-monthly').click();
    const printPage = await popup;
    await printPage.setViewportSize({width:740,height:860});
    await printPage.getByRole('heading',{name:'月案の印刷確認'}).waitFor();
    await printPage.evaluate(()=>document.fonts.ready);
    await printPage.locator('header').screenshot({path:path.join(out,'monthly-print.jpg'),quality:94});
    await printPage.close();
    await shot('monthly-person','#form .roster');
    await shot('monthly-save','#undo','#save');
    await loc('#save').click();
    await shown('#message','保存しました');
    card=await openPeriod('monthly','2026-11','1');
    await shot('monthly-saved','[data-period="2026-11"]');
    await card.getByText('自園の帳票を開く').click();
    assert.equal(await loc('[data-cell="common:goal"]').inputValue(),goal);
    assert.ok((await loc('[data-cell="child:1:life"]').inputValue()).includes('タオル'));
    card=await openPeriod('monthly','2026-11','4','2');
    await card.getByText('自園の帳票で作成').click();
    await loc('.group-grid textarea').first().fill('安心して気持ちを伝える。');
    await shot('monthly-group','.group-grid thead','.group-grid tbody tr:first-child');
    await loc('#save').click();
    await shown('#message','保存しました');
    card=await openPeriod('monthly','2026-11','4','2');
    await card.getByText('自園の帳票を開く').click();
    assert.equal(await loc('.group-grid textarea').inputValue(),'安心して気持ちを伝える。');
    console.log('Month saved and reopened, both age layouts captured.');

    card=await openPeriod('weekly','2026-11-02','1');
    await resize(750);
    await shot('weekly-choose','[data-period="2026-11-02"] .calendar-card-heading');
    await card.getByText('自園の帳票で作成').click();
    await resize(1490);
    await loc('.source-card summary').click();
    await shot('weekly-copy','.source-card[open]');
    await loc('.source-detail [data-copy]').click();
    await shown('#weekly-message','選択中の週へコピーしました');
    const activity='園庭で落ち葉を集める。';
    let row=page.locator('.infant-paper tr').filter({has:page.locator('[data-start="2026-11-02"]')});
    await row.locator('[data-field=aim]').fill('秋の自然に親しむ。');
    await row.locator('[data-field=activity]').fill(activity);
    await shot('weekly-infant','.infant-paper thead','.infant-paper tr.selected-row');
    const parent=page.locator('[name=parent_document_id]');
    await parent.selectOption({index:1});
    const monthId=await parent.inputValue();
    await resize(750);
    await shot('weekly-month','section:has(> h2:text-is("月案との接続")) h2','label:has(> select[name=parent_document_id])');
    await resize(1490);
    await shot('weekly-save','#weekly-cancel','#weekly-save');
    await loc('#weekly-save').click();
    await shown('#weekly-message','週案1件を保存しました');
    card=await openPeriod('weekly','2026-11-02','1');
    await resize(750);
    await shot('weekly-saved','[data-period="2026-11-02"] .calendar-card-heading','[data-period="2026-11-02"] p:nth-of-type(2)');
    await card.getByText('自園の帳票を開く').click();
    await resize(1490);
    assert.equal(await loc('[data-start="2026-11-02"][data-field=activity]').inputValue(),activity);
    assert.equal(await parent.inputValue(),monthId);
    card=await openPeriod('weekly','2026-11-02','4','2');
    await card.getByText('自園の帳票で作成').click();
    await loc('[data-field=activity][data-day="0"]').fill('色や形のちがう落ち葉を探す。');
    await shot('weekly-days','#paper-fields .paper-table thead','#paper-fields .paper-table tbody tr:first-child');
    await loc('#weekly-save').click();
    await shown('#weekly-message','週案1件を保存しました');
    card=await openPeriod('weekly','2026-11-02','4','2');
    await card.getByText('自園の帳票を開く').click();
    assert.equal(await loc('[data-field=activity][data-day="0"]').inputValue(),'色や形のちがう落ち葉を探す。');
    console.log('Week saved and reopened, both age layouts captured.');

    const cal='/plans/daily-plans/?year=2026&month=11&classroom_ref='+encodeURIComponent('そら組');
    const cell=page.locator('a[aria-label^="11月11日 そら組"]');
    await go(cal);
    await shot('daily-choose','td:has(a[aria-label^="11月11日 そら組"])');
    await cell.click();
    await loc('#daily-draft [name=age_class]').selectOption({label:'3歳児'});
    await resize(780);
    await shot('daily-basics','#daily-draft .form-panel:first-of-type');
    const initialAim = '形の違いを楽しむ。';
    await loc('[name=daily_aims]').fill(initialAim);
    await loc('.daily-example-panel [name=age_class]').selectOption({label:'3歳児'});
    await loc('.daily-example-panel [name=month]').selectOption('8');
    await loc('.daily-example-panel button[type=submit]').click();
    await shown('.daily-example-summary','粘土遊び');
    assert.equal(await loc('[name=daily_aims]').inputValue(),initialAim);
    await loc('.daily-example-summary').click();
    await shot('daily-copy','.daily-example-card[open]');
    await loc('.daily-example-copy').click();
    await shot('daily-copy-choice','#daily-copy-choice[open]');
    await loc('#daily-copy-choice button[value=append]').click();
    await shown('#daily-example-feedback','文例を追加しました');
    assert.ok((await loc('[name=daily_aims]').inputValue()).startsWith(initialAim+'\n'));
    await loc('[name=daily_aims]').fill('粘土の感触を楽しむ。');
    await shot('daily-aims','#daily-draft .form-panel:has([name=daily_aims])');
    await resize(1490);
    await loc('[name=timeline_time]').fill('10:00');
    await loc('[name=timeline_children]').fill('粘土を丸めたり伸ばしたりする。');
    await loc('[name=timeline_support]').fill('作りたい形に合わせて声をかける。');
    await loc('[name=timeline_considerations]').fill('道具を使う場所を確かめる。');
    await shot('daily-flow','#daily-draft .daily-plan-edit-grid thead','#daily-timeline-rows tr:first-child');
    await shot('daily-save','#daily-draft .form-actions a','#daily-draft button[type=submit]');
    await loc('#daily-draft button[type=submit]').click();
    await loc('.document-header').waitFor();
    await go(cal);
    await cell.click();
    await loc('.document-header').waitFor();
    await resize(750);
    await shot('daily-saved','.document-header');
    await loc('#daily-reflection-form textarea').fill('粘土を丸めながら、友だちと形を見せ合っていた。');
    await loc('#daily-reflection-form button[value=draft]').click();
    await shown('#daily-reflection-status','振り返りの下書きを保存しました。');
    await shot('daily-reflection','.daily-reflection-panel');
    await loc('#daily-reflection-form button[value=submit]').click();
    await shot('daily-confirm','.reflection-review-page');
    await page.getByRole('button',{name:'管理者へ承認を依頼'}).click();
    await shown('.reflection-review-page','承認待ち');
    await shot('daily-pending','.reflection-review-page');
    await page.getByRole('link',{name:'入力・承認状況へ戻る'}).click();
    await page.getByRole('link',{name:'修正',exact:true}).click();
    const time=loc('input[name^=rowtime__]');
    await time.fill('10:15');
    await page.getByRole('button',{name:'修正を保存',exact:true}).click();
    await loc('.document-header').waitFor();
    await page.getByRole('link',{name:'修正',exact:true}).click();
    assert.equal(await time.inputValue(),'10:15');
    console.log('Day saved and reopened. Example appended and reflection request verified in the disposable fixture.');
  } finally {
    if(browser) await browser.close();
    if(server.exitCode===null) server.kill();
  }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
